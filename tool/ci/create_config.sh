#!/usr/bin/env bash
# Creates the git-ignored config files the app needs to compile in CI.
#
# Each file is taken from a base64 secret when available, otherwise a stub is
# generated. Stubs are enough to analyze, test and build a debug APK, but the
# resulting app cannot talk to Firebase. Existing files are never overwritten.
#
#   FIREBASE_OPTIONS_DART_B64  -> lib/firebase_options.dart
#   ENV_DART_B64               -> lib/env.dart
#   GOOGLE_SERVICES_JSON_B64   -> android/app/google-services.json
set -euo pipefail

write_file() {
  local path=$1 secret=$2 stub=$3
  if [[ -f "$path" ]]; then
    echo "keep   $path (already exists)"
  elif [[ -n "$secret" ]]; then
    echo "$secret" | base64 --decode > "$path"
    echo "secret $path"
  else
    printf '%s\n' "$stub" > "$path"
    echo "stub   $path"
  fi
}

write_file lib/env.dart "${ENV_DART_B64:-}" "$(cat lib/env_example.dart)"

write_file lib/firebase_options.dart "${FIREBASE_OPTIONS_DART_B64:-}" "\
// CI stub generated by tool/ci/create_config.sh. Not a real Firebase project.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform => android;

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: 'ci-stub',
    appId: '1:000000000000:android:0000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'ci-stub',
  );
}"

write_file android/app/google-services.json "${GOOGLE_SERVICES_JSON_B64:-}" '{
  "project_info": {
    "project_number": "000000000000",
    "project_id": "ci-stub",
    "storage_bucket": "ci-stub.appspot.com"
  },
  "client": [
    {
      "client_info": {
        "mobilesdk_app_id": "1:000000000000:android:0000000000000000",
        "android_client_info": { "package_name": "dev.armandohackcode.app_events" }
      },
      "oauth_client": [],
      "api_key": [{ "current_key": "ci-stub" }],
      "services": { "appinvite_service": { "other_platform_oauth_client": [] } }
    }
  ],
  "configuration_version": "1"
}'
