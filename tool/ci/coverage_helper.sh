#!/usr/bin/env bash
# Generates a test that imports every file in lib/ so `flutter test --coverage`
# reports untested files as 0% instead of silently omitting them.
set -euo pipefail
out=test/coverage_helper_test.dart
{
  echo '// GENERATED by tool/ci/coverage_helper.sh. Do not commit.'
  echo '// ignore_for_file: unused_import, depend_on_referenced_packages'
  find lib -name '*.dart' ! -name '*.g.dart' ! -name 'env.dart' ! -name 'env_example.dart' ! -name 'firebase_options.dart' | sort |
    sed "s#^lib/\(.*\)#import 'package:app_events/\1';#"
  echo 'void main() {}'
} > "$out"
dart format "$out" >/dev/null
echo "Generated $out"
